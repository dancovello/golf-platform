import type { Access, CollectionConfig, Config, Field, Plugin } from 'payload'

import { isSuperAdmin } from '../access/roles'
import { isFullyAuthenticated } from './fullyAuthenticated'
import { sendEmailCodeEndpoint, verifyEmailCodeEndpoint } from './emailCodeEndpoints'

/**
 * The sign-in code, with payload-totp's authenticator app taken out (decisions.md, 3 Nov).
 *
 * payload-totp still does the part that works: it holds the "code entered" cookie and refuses
 * access to everything until it is there. This plugin, which must run after it, changes what
 * proves the code and keeps the rule for super-admins:
 *
 * 1. **The code is emailed, not generated by an app.** `/api/verify-totp` checks the emailed
 *    six digits (src/auth/emailCodeEndpoints.ts) and `/api/send-email-code` sends them. The
 *    authenticator set-up and switch-off endpoints, screens and account-page field are gone.
 * 2. **Super-admins always need a code.** `hasTotp` ("this account has a second step") is true
 *    for every super-admin, whatever is in the old secret column. Club editors keep it only if
 *    they had set the authenticator up before; otherwise a password is enough (22 Oct).
 * 3. **Access:** every collection and settings rule refuses a super-admin who hasn't entered
 *    their code, apart from reading their own account (the code screen needs it).
 */
const OPERATIONS = ['create', 'read', 'update', 'delete', 'readVersions', 'unlock'] as const

const VERIFY_VIEW = '/admin/EmailCodeVerify#EmailCodeVerify'
const SETUP_VIEW = '/admin/EmailCodeSetupRedirect#EmailCodeSetupRedirect'

/** Wraps one access rule: a super-admin without their code gets nothing (or only their own
 * account, for reading users). */
export const withSuperAdminCode =
  (rule: Access, ownAccountOnly: boolean): Access =>
  (args) => {
    const user = args.req.user
    if (user && isSuperAdmin(user) && !isFullyAuthenticated(user)) {
      return ownAccountOnly ? { id: { equals: user.id } } : false
    }
    return rule(args)
  }

/** The users collection's fields: no authenticator set-up field, and `hasTotp` also true for
 * every super-admin. */
const userFields = (fields: Field[]): Field[] =>
  fields
    .filter((field) => !('name' in field && field.name === 'totpSecretUI'))
    .map((field) => {
      if (!('name' in field) || field.name !== 'hasTotp' || field.type !== 'checkbox') return field
      return {
        ...field,
        hooks: {
          ...field.hooks,
          afterRead: [
            ...(field.hooks?.afterRead ?? []),
            ({ data, value }) => (isSuperAdmin(data) ? true : value),
          ],
        },
      }
    })

/** The wrong-guess counter's row also holds the current emailed code (src/auth/emailCode.ts):
 * a keyed fingerprint of it, when it expires and when it was sent. Never the code itself. */
const withCodeColumns = (collection: CollectionConfig): CollectionConfig => ({
  ...collection,
  fields: [
    ...collection.fields,
    { name: 'codeHash', type: 'text' },
    { name: 'codeExpires', type: 'date' },
    { name: 'codeSentAt', type: 'date' },
  ],
})

export const superAdminTwoFactor: Plugin = (config: Config): Config => {
  let attemptsFound = false
  let usersFound = false
  const collections = (config.collections ?? []).map((collection) => {
    if (collection.slug === 'totp-attempts') {
      attemptsFound = true
      return withCodeColumns(collection)
    }
    const access = { ...collection.access }
    for (const op of OPERATIONS) {
      const rule = access[op]
      if (typeof rule === 'function') {
        access[op] = withSuperAdminCode(
          rule as Access,
          collection.slug === 'users' && op === 'read',
        )
      }
    }
    if (collection.slug !== 'users') return { ...collection, access }
    usersFound = true
    return { ...collection, access, fields: userFields(collection.fields) }
  })
  const globals = (config.globals ?? []).map((global) => {
    const access = { ...global.access }
    for (const op of ['read', 'update', 'readVersions'] as const) {
      const rule = access[op]
      if (typeof rule === 'function') access[op] = withSuperAdminCode(rule as Access, false)
    }
    return { ...global, access }
  })

  // The authenticator endpoints go; the code check keeps the same address, and sending is new.
  let verifyFound = false
  const endpoints = (config.endpoints ?? []).flatMap((endpoint) => {
    if (endpoint.path === '/setup-totp' || endpoint.path === '/remove-totp') return []
    if (endpoint.path === '/verify-totp') {
      verifyFound = true
      return [verifyEmailCodeEndpoint]
    }
    return [endpoint]
  })
  if (!verifyFound || !attemptsFound || !usersFound) {
    throw new Error('superAdminTwoFactor: payload-totp not found; it must run after payloadTotp')
  }

  // The plugin's screens: ours asks for the emailed code, and the old set-up address just
  // forwards to the admin (bookmarks and old links).
  const views = Object.fromEntries(
    Object.entries(config.admin?.components?.views ?? {}).map(([key, view]) => {
      if (key === 'VerifyTOTP' || key === 'VerifyTOTPBackslash') {
        return [key, { ...view, Component: VERIFY_VIEW }]
      }
      if (key === 'SetupTOTP' || key === 'SetupTOTPBackslash') {
        return [key, { ...view, Component: SETUP_VIEW }]
      }
      return [key, view]
    }),
  )

  return {
    ...config,
    collections,
    globals,
    endpoints: [...endpoints, sendEmailCodeEndpoint],
    admin: {
      ...config.admin,
      components: { ...config.admin?.components, views },
    },
  }
}
